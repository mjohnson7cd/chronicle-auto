package io.github.mjohnson7cd.chronicleauto.data.sources.plex.model

import com.squareup.moshi.JsonClass
import io.github.mjohnson7cd.chronicleauto.data.model.Chapter

@JsonClass(generateAdapter = true)
data class PlexChapter(
    val id: Long = 0L,
    val filter: String = "",
    val tag: String = "",
    val index: Long = 0L,
    val discNumber: Int = 0,
    val startTimeOffset: Long = 0L,
    val endTimeOffset: Long = 0L,
)

fun PlexChapter.toChapter(
    trackId: String,
    trackDiscNumber: Int,
    downloaded: Boolean,
    bookId: String,
): Chapter {
    return Chapter(
        uid = 0L, // Auto-generated by Room
        title = tag.takeIf { it.isNotEmpty() } ?: "Chapter $index",
        id = id,
        index = index,
        discNumber = discNumber.takeIf { it != 0 } ?: trackDiscNumber,
        startTimeOffset = startTimeOffset,
        endTimeOffset = endTimeOffset,
        downloaded = downloaded,
        trackId = trackId,
        bookId = bookId,
    )
}
